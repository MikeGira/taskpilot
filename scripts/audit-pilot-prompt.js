const fs = require('fs');
const { isAuditPass } = require('./lib/audit-parse');

const ANTHROPIC_KEY = process.env.ANTHROPIC_API_KEY;
const GH_TOKEN = process.env.GH_TOKEN;
const REPO = process.env.REPO;

if (!GH_TOKEN) { console.error('Missing required env var: GH_TOKEN'); process.exit(1); }
if (!REPO) { console.error('Missing required env var: REPO'); process.exit(1); }
if (!ANTHROPIC_KEY) {
  console.warn('ANTHROPIC_API_KEY not configured in repo secrets — skipping audit.');
  console.warn('To enable: Settings → Secrets → Actions → New secret → ANTHROPIC_API_KEY');
  process.exit(0);
}

function readFile(filePath) {
  try { return fs.readFileSync(filePath, 'utf8'); } catch { return ''; }
}

function extractFeatures() {
  const features = [];

  const routeTs = readFile('src/app/api/assistant/route.ts');
  const systemMatch = routeTs.match(/const SYSTEM\s*=\s*`([\s\S]*?)`;/);
  const systemPrompt = systemMatch ? systemMatch[1].trim() : '';

  const chatWidget = readFile('src/components/assistant/chat-widget.tsx');
  const welcomeMatch = chatWidget.match(/const WELCOME\s*=\s*"([^"]+)"/);
  const welcome = welcomeMatch ? welcomeMatch[1] : '';

  if (fs.existsSync('src/app/api/generate/route.ts')) features.push('AI Script Generator at /generate');
  if (fs.existsSync('src/app/api/workflow')) features.push('n8n Workflow Generator at /workflow');
  if (fs.existsSync('src/app/api/stripe')) features.push('Stripe payments integration');

  const kitMatch = readFile('src/app/api/assistant/route.ts').match(/\$(\d+).*?kit/i);
  if (kitMatch) features.push(`Starter Kit at $${kitMatch[1]}`);

  return { systemPrompt, welcome, features };
}

async function callClaude(systemPrompt, welcome, features) {
  const featuresText = features.length ? features.join('\n- ') : 'No additional features detected.';
  const userMessage = `You are auditing an AI assistant system prompt for accuracy and completeness.

SYSTEM PROMPT UNDER REVIEW:
${systemPrompt}

WELCOME MESSAGE UNDER REVIEW:
${welcome}

PLATFORM FEATURES DETECTED IN CODEBASE:
- ${featuresText}

Task: Identify any gaps between the system prompt / welcome message and the detected platform features. Look for:
1. Features present in the codebase but not mentioned in the system prompt
2. Outdated or inaccurate descriptions of features
3. Missing capabilities that users would need to know about

If everything looks accurate and complete, respond with exactly: PASS
If there are gaps, describe them clearly and concisely. Do not include minor style suggestions.`;

  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-api-key': ANTHROPIC_KEY,
      'anthropic-version': '2023-06-01',
    },
    body: JSON.stringify({
      model: 'claude-haiku-4-5-20251001',
      max_tokens: 1024,
      messages: [{ role: 'user', content: userMessage }],
    }),
  });

  if (!res.ok) {
    const err = await res.text();
    throw new Error(`Anthropic API error ${res.status}: ${err}`);
  }

  const data = await res.json();
  return data.content?.[0]?.text ?? '';
}

async function getOpenAuditIssues() {
  const res = await fetch(
    `https://api.github.com/repos/${REPO}/issues?labels=ai-audit&state=open`,
    { headers: { Authorization: `Bearer ${GH_TOKEN}`, Accept: 'application/vnd.github+json' } }
  );
  if (!res.ok) return [];
  const issues = await res.json();
  return Array.isArray(issues) ? issues : [];
}

async function closeIssue(number) {
  await fetch(`https://api.github.com/repos/${REPO}/issues/${number}`, {
    method: 'PATCH',
    headers: { Authorization: `Bearer ${GH_TOKEN}`, Accept: 'application/vnd.github+json', 'Content-Type': 'application/json' },
    body: JSON.stringify({ state: 'closed', state_reason: 'completed' }),
  });
  console.log(`Closed resolved audit issue #${number}`);
}

async function createIssue(findings) {
  const today = new Date().toISOString().slice(0, 10);
  const body = `## Pilot AI Prompt Audit — ${today}

The automated audit found gaps between the Pilot system prompt and the detected platform features.

### Findings

${findings}

### Next Steps

1. Review the findings above
2. Update \`src/app/api/assistant/route.ts\` (SYSTEM constant) and/or \`src/components/assistant/chat-widget.tsx\` (WELCOME constant)
3. Close this issue once the prompt is updated

---
*Generated by the automated [Pilot AI Audit](../../actions/workflows/ai-audit.yml) workflow.*`;

  const res = await fetch(`https://api.github.com/repos/${REPO}/issues`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${GH_TOKEN}`,
      Accept: 'application/vnd.github+json',
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      title: `Pilot AI Prompt Audit: gaps found [${today}]`,
      body,
      labels: ['ai-audit'],
    }),
  });

  if (!res.ok) {
    const err = await res.text();
    throw new Error(`GitHub API error ${res.status}: ${err}`);
  }

  const issue = await res.json();
  console.log(`Issue created: ${issue.html_url}`);
}

async function main() {
  const { systemPrompt, welcome, features } = extractFeatures();

  if (!systemPrompt) {
    console.error('Could not extract SYSTEM prompt from route.ts — check the file.');
    process.exit(1);
  }

  console.log(`Extracted system prompt (${systemPrompt.length} chars), ${features.length} platform features.`);

  const result = await callClaude(systemPrompt, welcome, features);
  console.log('Claude audit result:', result.slice(0, 200));

  const openIssues = await getOpenAuditIssues();

  // Shared, unit-tested detector (scripts/lib/audit-parse.js). The old whole/last-line
  // check would have filed a spurious issue for a "PASS\n\n<prose>" response (the #74
  // failure mode) — this findings format is free prose, so a positional PASS check is
  // the only reliable signal.
  if (isAuditPass(result)) {
    console.log('Audit passed — no issues to report.');
    for (const issue of openIssues) await closeIssue(issue.number);
    return;
  }

  if (openIssues.length > 0) {
    console.log(`An open ai-audit issue already exists (#${openIssues[0].number}) — skipping duplicate.`);
    return;
  }

  await createIssue(result);
}

main().catch(err => { console.error(err); process.exit(1); });
